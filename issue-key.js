#!/usr/bin/env node
/**
 * Bill Pro device-bound licence issuer (SELLER PC ONLY).
 *
 *   node issue-key.js BP-XXXX-XXXX-XXXX
 *   node issue-key.js BP-XXXX-XXXX-XXXX --key C:\backup\bill-pro-license-private.jwk
 *
 * The customer reads their Device ID off the activation screen and sends it
 * to you (WhatsApp). You run this, send back the printed BP- key, they paste
 * it to activate. One key works on ONE device: verification compares the
 * embedded ID against the phone's hardware-derived ID and checks the ECDSA
 * signature with the public key shipped in the app.
 *
 * The private key NEVER leaves this machine. PD- pool keys are generated by
 * generate-keys.js; replacing that pool invalidates every key from the old batch.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { normalizeDeviceId, b32encode, groupsOf } from './license-codec.js';

const ROOT = path.dirname(fileURLToPath(import.meta.url));

const argv = process.argv.slice(2).filter((arg) => !arg.startsWith('--key='));
const keyFlag = process.argv.slice(2).find((arg) => arg.startsWith('--key='));
const keyPath = keyFlag
  ? path.resolve(keyFlag.slice('--key='.length))
  : process.env.BILL_PRO_PRIVATE_JWK
    ? path.resolve(process.env.BILL_PRO_PRIVATE_JWK)
    : path.join(ROOT, 'bill-pro-license-private.jwk');

const deviceId = normalizeDeviceId(argv[0]);
if (!deviceId) {
  console.error('Usage: node issue-key.js BP-XXXX-XXXX-XXXX [--key=path-to-private.jwk]');
  console.error('The Device ID has 12 characters (digits + capital letters, no I/O).');
  process.exit(1);
}
if (!fs.existsSync(keyPath)) {
  console.error(`Private key not found: ${keyPath}`);
  console.error('Run node generate-license-keypair.js first (once, then back it up).');
  process.exit(1);
}

let privateKey;
try {
  const jwk = JSON.parse(fs.readFileSync(keyPath, 'utf8'));
  privateKey = crypto.createPrivateKey({ key: jwk, format: 'jwk' });
} catch (error) {
  console.error(`Cannot read private key: ${error.message}`);
  process.exit(1);
}

const signature = crypto.sign('sha256', Buffer.from(deviceId, 'utf8'), { key: privateKey, dsaEncoding: 'ieee-p1363' });
if (signature.length !== 64) {
  console.error(`Unexpected signature length: ${signature.length} (expected 64).`);
  process.exit(1);
}
const key = `BP-${groupsOf(deviceId + b32encode(signature), 5)}`;

console.log(`Device : BP-${groupsOf(deviceId, 4)}`);
console.log(`Key    : ${key}`);
console.log('');
console.log('Send the key to the customer (WhatsApp paste works best - it is long).');
