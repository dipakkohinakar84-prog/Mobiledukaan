#!/usr/bin/env node
/**
 * Bill Pro licence key generator.
 *
 *   node generate-keys.js               generate 5000 keys (appends to the existing batch)
 *   node generate-keys.js 2000          generate 2000 keys
 *   node generate-keys.js 5000 --replace  discard the old batch and start fresh
 *
 * Writes two files:
 *   keys.txt         - plaintext keys you sell. NEVER commit this (already gitignored).
 *   license-keys.js  - SHA-256 hashes only, bundled into the app. Publishing the
 *                      hashes is safe: they cannot be reversed into keys.
 *
 * Append is the default so keys sold from an earlier batch stay valid.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const KEYS_FILE = path.join(ROOT, 'keys.txt');
const HASH_MODULE = path.join(ROOT, 'license-keys.js');
const PUBLIC_HASH_JSON = path.join(ROOT, 'public', 'license-hashes.json');

// 32 characters, no I / O / 0 / 1 so keys cannot be misread over the phone.
const CHARSET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
const SEGMENTS = 3;
const SEG_LEN = 4;
const HEX64 = /[0-9a-f]{64}/g;

const argv = process.argv.slice(2);
const replace = argv.includes('--replace');
const countArg = argv.find((arg) => /^\d+$/.test(arg));
const COUNT = countArg ? Number(countArg) : 5000;

if (!Number.isInteger(COUNT) || COUNT < 1 || COUNT > 100000) {
  console.error('Usage: node generate-keys.js [count] [--replace]');
  process.exit(1);
}

const segment = () =>
  Array.from({ length: SEG_LEN }, () => CHARSET[crypto.randomInt(CHARSET.length)]).join('');

const makeKey = () => `PD-${Array.from({ length: SEGMENTS }, segment).join('-')}`;

const hashKey = (key) => crypto.createHash('sha256').update(key, 'utf8').digest('hex');

const readExistingHashes = () => {
  if (replace || !fs.existsSync(HASH_MODULE)) return new Set();
  return new Set(fs.readFileSync(HASH_MODULE, 'utf8').match(HEX64) || []);
};

const existing = readExistingHashes();
const existingCount = existing.size;

const keys = new Set();
const hashes = new Set(existing);
const guardStart = Date.now();
while (keys.size < COUNT) {
  if (Date.now() - guardStart > 30000) {
    console.error('Generation stalled - aborting.');
    process.exit(1);
  }
  const key = makeKey();
  const digest = hashKey(key);
  if (existing.has(digest)) continue;
  keys.add(key);
  hashes.add(digest);
}

const keyList = [...keys];
const hashList = [...hashes];
const stamp = new Date().toISOString();

const moduleText = [
  '// Generated by generate-keys.js - do not edit by hand.',
  '// SHA-256 hashes of valid Bill Pro licence keys. Safe to publish: a hash',
  '// cannot be reversed into the key it came from.',
  `// ${hashList.length} key(s) as of ${stamp}`,
  '',
  'export const BILL_PRO_KEY_HASHES = new Set([',
  ...hashList.map((hash) => `    "${hash}",`),
  ']);',
  '',
].join('\n');
fs.writeFileSync(HASH_MODULE, moduleText, 'utf8');
fs.writeFileSync(PUBLIC_HASH_JSON, JSON.stringify(hashList) + '\n', 'utf8');

const keyHeader = [
  '# PhoneDukaan Bill Pro licence keys',
  `# Batch: ${keyList.length} new key(s) generated ${stamp}`,
  '# Total keys ever generated: ' + hashList.length,
  '# KEEP THIS FILE PRIVATE. One key per customer.',
  '# Format: PD-XXXX-XXXX-XXXX',
  '',
].join('\n');

if (!replace && fs.existsSync(KEYS_FILE)) {
  fs.appendFileSync(KEYS_FILE, keyHeader + keyList.join('\n') + '\n', 'utf8');
} else {
  fs.writeFileSync(KEYS_FILE, keyHeader + keyList.join('\n') + '\n', 'utf8');
}

console.log(`✓ ${keyList.length} new key(s) written to keys.txt`);
console.log(`✓ ${hashList.length} total hash(es) written to license-keys.js`);
if (existingCount && !replace) console.log(`  (kept ${existingCount} key(s) from the previous batch)`);
if (replace) console.log('  (--replace: previous batch is no longer valid)');
console.log('\nNext: npm run build');
